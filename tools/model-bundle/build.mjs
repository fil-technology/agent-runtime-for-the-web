#!/usr/bin/env node
/**
 * Builds an upload-ready folder of on-device model weights.
 *
 * The layout matches what transformers.js requests, so pointing the runtime at
 * your bucket is a one-line change:
 *
 *   createLocalProvider({ weightsHost: "https://models.example.com/" })
 *
 * Large files are stored brotli-compressed. The hub serves weights
 * uncompressed, but q4 ONNX compresses to roughly 41% of its size, so this is
 * the single biggest saving available on first load.
 */
import { createWriteStream } from "node:fs";
import { mkdir, rm, stat, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { pipeline } from "node:stream/promises";
import { brotliCompressSync, createBrotliCompress, constants as zlib } from "node:zlib";
import { Readable } from "node:stream";

const HUB = "https://huggingface.co";
const REVISION = "main";

/** Files transformers.js fetches for a text-generation pipeline. */
const SUPPORT_FILES = [
  "config.json",
  "generation_config.json",
  "tokenizer.json",
  "tokenizer_config.json",
  "special_tokens_map.json",
];

/** Compressing tiny JSON is pointless; anything above this is worth it. */
const COMPRESS_OVER_BYTES = 256 * 1024;

const args = process.argv.slice(2);
const flag = (name, fallback) => {
  const index = args.indexOf(`--${name}`);
  return index >= 0 ? args[index + 1] : fallback;
};

const model = flag("model", "HuggingFaceTB/SmolLM2-360M-Instruct");
const dtype = flag("dtype", "q4");
const quality = Number(flag("quality", "5"));
const outDir = flag("out", "out");

const weightFile = `onnx/model_${dtype}.onnx`;
const files = [...SUPPORT_FILES, weightFile];

console.log(`\nmodel    ${model}`);
console.log(`dtype    ${dtype}`);
console.log(`brotli   quality ${quality}`);
console.log(`out      ${outDir}/\n`);

await rm(outDir, { recursive: true, force: true });

const manifest = [];
let rawTotal = 0;
let storedTotal = 0;

for (const file of files) {
  const url = `${HUB}/${model}/resolve/${REVISION}/${file}`;
  const key = `${model}/resolve/${REVISION}/${file}`;
  const response = await fetch(url);

  if (!response.ok) {
    // Optional files legitimately 404 on some repos.
    if (response.status === 404 && SUPPORT_FILES.includes(file)) {
      console.log(`skip     ${file} (not published for this model)`);
      continue;
    }
    throw new Error(
      `${file} -> HTTP ${response.status}. ` +
        `Check that "${model}" exists and publishes ONNX weights.`
    );
  }

  const target = join(outDir, key);
  await mkdir(dirname(target), { recursive: true });
  process.stdout.write(`fetch    ${file} … `);

  // content-length is not always present once redirects are followed, so the
  // decision to compress is made on real bytes, never on the header.
  const isWeights = file.endsWith(".onnx") || file.endsWith(".onnx_data");
  let declared = 0;
  let compress = false;

  if (isWeights) {
    declared = Number(response.headers.get("content-length") ?? 0);
    compress = true;
    await pipeline(
      Readable.fromWeb(response.body),
      createBrotliCompress({
        params: {
          [zlib.BROTLI_PARAM_QUALITY]: quality,
          ...(declared ? { [zlib.BROTLI_PARAM_SIZE_HINT]: declared } : {}),
        },
      }),
      createWriteStream(target)
    );
    if (!declared) declared = (await stat(target)).size;
  } else {
    const body = Buffer.from(await response.arrayBuffer());
    declared = body.length;
    compress = body.length >= COMPRESS_OVER_BYTES;
    await writeFile(
      target,
      compress
        ? brotliCompressSync(body, {
            params: {
              [zlib.BROTLI_PARAM_QUALITY]: quality,
              [zlib.BROTLI_PARAM_SIZE_HINT]: body.length,
            },
          })
        : body
    );
  }

  const stored = (await stat(target)).size;
  rawTotal += declared;
  storedTotal += stored;

  manifest.push({
    key,
    contentType: file.endsWith(".json") ? "application/json" : "application/octet-stream",
    contentEncoding: compress ? "br" : undefined,
    rawBytes: declared,
    storedBytes: stored,
  });

  console.log(
    compress
      ? `${mb(declared)} → ${mb(stored)} br (${Math.round((stored / declared) * 100)}%)`
      : `${mb(declared)}`
  );
}

await writeFile(join(outDir, "manifest.json"), JSON.stringify({ model, dtype, revision: REVISION, files: manifest }, null, 2));

/* ------------------------------- upload -------------------------------- */

const bucket = flag("bucket", "YOUR_BUCKET");
const lines = [
  "#!/usr/bin/env bash",
  "# Generated by tools/model-bundle. Run from inside the output folder.",
  "#",
  "# Content-Encoding is set on the object itself: R2 will not compress a",
  "# 370MB binary on the fly, so it is stored pre-compressed and the browser",
  "# decompresses transparently.",
  "set -euo pipefail",
  `BUCKET="\${1:-${bucket}}"`,
  "",
];
for (const entry of manifest) {
  const encoding = entry.contentEncoding ? ` \\\n    --content-encoding ${entry.contentEncoding}` : "";
  lines.push(
    `wrangler r2 object put "$BUCKET/${entry.key}" \\\n    --file "${entry.key}" \\\n    --content-type ${entry.contentType}${encoding} \\\n    --cache-control "public, max-age=31536000, immutable"`,
    ""
  );
}
await writeFile(join(outDir, "upload.sh"), lines.join("\n"), { mode: 0o755 });

await writeFile(
  join(outDir, "cors.json"),
  JSON.stringify(
    [
      {
        AllowedOrigins: ["https://your-app.example.com", "http://localhost:3000"],
        AllowedMethods: ["GET", "HEAD"],
        AllowedHeaders: ["range", "if-match", "accept-encoding"],
        ExposeHeaders: ["content-length", "content-encoding", "content-range", "etag"],
        MaxAgeSeconds: 86400,
      },
    ],
    null,
    2
  )
);

console.log(`\ntotal    ${mb(rawTotal)} raw → ${mb(storedTotal)} stored (${Math.round((storedTotal / rawTotal) * 100)}%)`);
console.log(`\nnext:`);
console.log(`  cd ${outDir} && ./upload.sh your-bucket-name`);
console.log(`  wrangler r2 bucket cors put your-bucket-name --rules ./cors.json`);
console.log(`\nthen point the runtime at it:`);
console.log(`  createLocalProvider({ model: "${model}", weightsHost: "https://<your-domain>/" })\n`);

function mb(bytes) {
  return `${(bytes / 1048576).toFixed(1)} MB`;
}
